-- Cross-workspace references are rejected even if a caller knows another
-- tenant's UUID. Existing single-column FKs remain in place so their original
-- delete behaviour is preserved; these composite FKs add tenant consistency.
do $$
declare
  relation record;
  delete_clause text;
begin
  for relation in
    select * from (values
      ('staff_users','branch_id','branches','set null'),
      ('properties','branch_id','branches','restrict'),
      ('properties','assigned_agent_id','staff_users','set null'),
      ('property_images','property_id','properties','cascade'),
      ('property_documents','property_id','properties','cascade'),
      ('leads','property_id','properties','set null'),
      ('leads','branch_id','branches','restrict'),
      ('leads','assigned_agent_id','staff_users','set null'),
      ('activity_logs','branch_id','branches','set null'),
      ('activity_logs','property_id','properties','set null'),
      ('activity_logs','lead_id','leads','set null'),
      ('activity_logs','staff_user_id','staff_users','set null'),
      ('lead_communication_logs','lead_id','leads','cascade'),
      ('lead_communication_logs','staff_user_id','staff_users','set null'),
      ('app_settings','updated_by','staff_users','set null'),
      ('cms_homepage_content','updated_by','staff_users','set null'),
      ('cms_banners','updated_by','staff_users','set null'),
      ('cms_team_profiles','staff_user_id','staff_users','set null'),
      ('cms_team_profiles','updated_by','staff_users','set null'),
      ('cms_testimonials','updated_by','staff_users','set null'),
      ('cms_featured_properties','property_id','properties','cascade'),
      ('cms_featured_properties','updated_by','staff_users','set null'),
      ('cms_services_section','updated_by','staff_users','set null'),
      ('cms_service_cards','section_id','cms_services_section','restrict'),
      ('cms_service_cards','updated_by','staff_users','set null')
    ) as x(child_table, child_column, parent_table, delete_action)
  loop
    if to_regclass(format('public.%I', relation.child_table)) is not null
       and to_regclass(format('public.%I', relation.parent_table)) is not null
       and not exists (
         select 1 from pg_constraint
         where conrelid = format('public.%I', relation.child_table)::regclass
           and conname = relation.child_table || '_' || relation.child_column || '_workspace_fkey'
       ) then
      delete_clause := case
        when relation.delete_action = 'set null'
          then format('set null (%I)', relation.child_column)
        else relation.delete_action
      end;
      execute format(
        'alter table public.%I add constraint %I foreign key (%I, workspace_id) references public.%I(id, workspace_id) on delete %s',
        relation.child_table,
        relation.child_table || '_' || relation.child_column || '_workspace_fkey',
        relation.child_column,
        relation.parent_table,
        delete_clause
      );
    end if;
  end loop;
end;
$$;

-- Migrate every existing authenticated Hilltop staff identity into the
-- template workspace without changing or deleting the staff row.
insert into public.demo_workspace_memberships (
  workspace_id,
  auth_user_id,
  role,
  status,
  is_current,
  created_by
)
select
  su.workspace_id,
  su.auth_user_id,
  su.role,
  case when su.is_active then 'active' else 'revoked' end,
  su.is_active,
  su.auth_user_id
from public.staff_users su
where su.auth_user_id is not null
on conflict (workspace_id, auth_user_id) do update
set role = excluded.role,
    status = excluded.status,
    is_current = case
      when public.demo_workspace_memberships.is_current then true
      when excluded.status = 'active' and not exists (
        select 1 from public.demo_workspace_memberships current_membership
        where current_membership.auth_user_id = excluded.auth_user_id
          and current_membership.is_current = true
      ) then true
      else false
    end;

-- Private helpers are callable from policies/triggers but cannot be reached as
-- Data API RPC endpoints because the private schema is not exposed.
create or replace function private.current_demo_workspace_id()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select membership.workspace_id
  from public.demo_workspace_memberships membership
  join public.demo_workspaces workspace on workspace.id = membership.workspace_id
  where membership.auth_user_id = (select auth.uid())
    and membership.status = 'active'
    and membership.is_current = true
    and workspace.status = 'active'
  limit 1;
$$;

create or replace function private.default_demo_workspace_id()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select id
  from public.demo_workspaces
  where is_public_default = true
    and status = 'active'
  limit 1;
$$;

create or replace function private.is_current_workspace_super_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.demo_workspace_memberships membership
    join public.demo_workspaces workspace on workspace.id = membership.workspace_id
    where membership.auth_user_id = (select auth.uid())
      and membership.status = 'active'
      and membership.is_current = true
      and membership.role = 'super_admin'
      and workspace.status = 'active'
  );
$$;

create or replace function private.request_demo_workspace_id()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when (select auth.uid()) is null then private.default_demo_workspace_id()
    else private.current_demo_workspace_id()
  end;
$$;

revoke all on all functions in schema private from public;
grant usage on schema private to anon, authenticated;
grant execute on function private.current_demo_workspace_id() to authenticated;
grant execute on function private.default_demo_workspace_id() to anon, authenticated;
grant execute on function private.is_current_workspace_super_admin() to authenticated;
grant execute on function private.request_demo_workspace_id() to anon, authenticated;

-- A database trigger supplies workspace context for every insert. The browser
-- also sends workspace_id explicitly, but RLS/this trigger remain authoritative.
create or replace function private.assign_demo_workspace_id()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.workspace_id is null then
    new.workspace_id := private.request_demo_workspace_id();
  end if;

  if new.workspace_id is null then
    raise exception using
      errcode = '42501',
      message = 'No active demo workspace is available for this request.';
  end if;

  return new;
end;
$$;
revoke all on function private.assign_demo_workspace_id() from public;

do $$
declare
  table_name text;
  company_tables constant text[] := array[
    'branches','staff_users','properties','property_images','property_documents',
    'leads','activity_logs','lead_communication_logs','app_settings',
    'cms_homepage_content','cms_banners','cms_team_profiles','cms_testimonials',
    'cms_featured_properties','cms_service_showcase_items','cms_services_section',
    'cms_service_cards','team_members','market_price_statistics'
  ];
begin
  foreach table_name in array company_tables loop
    if to_regclass(format('public.%I', table_name)) is not null then
      execute format('drop trigger if exists %I on public.%I', 'trg_' || table_name || '_assign_workspace', table_name);
      execute format(
        'create trigger %I before insert on public.%I for each row execute function private.assign_demo_workspace_id()',
        'trg_' || table_name || '_assign_workspace',
        table_name
      );
    end if;
  end loop;
end;
$$;

