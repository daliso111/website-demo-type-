-- Workspace-aware storage paths. New uploads use <workspace-uuid>/... . The
-- default Hilltop workspace may still access legacy unprefixed objects so the
-- migration never requires destructive object moves.
create or replace function private.try_uuid(value text)
returns uuid
language plpgsql
immutable
set search_path = ''
as $$
begin
  return value::uuid;
exception when invalid_text_representation then
  return null;
end;
$$;

create or replace function private.storage_object_in_workspace(
  object_bucket text,
  object_name text,
  workspace_id uuid
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    workspace_id is not null
    and (
      (storage.foldername(object_name))[1] = workspace_id::text
      or (
        workspace_id = private.default_demo_workspace_id()
        and case
          when object_bucket in ('property-images', 'property-documents') then exists (
            select 1 from public.properties property
            where property.id = private.try_uuid((storage.foldername(object_name))[1])
              and property.workspace_id = workspace_id
          )
          else not exists (
            select 1 from public.demo_workspaces workspace
            where workspace.id = private.try_uuid((storage.foldername(object_name))[1])
          )
        end
      )
    );
$$;

