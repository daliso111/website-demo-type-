-- Existing role-sensitive property triggers must resolve the staff profile in
-- the current workspace. Membership role is the fallback for a newly-created
-- workspace that does not yet contain an operational staff profile.
create or replace function public.enforce_property_classification_management()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  staff_role text;
  staff_branch_id uuid;
begin
  if (select auth.uid()) is null then return new; end if;

  select coalesce(su.role, membership.role), su.branch_id
    into staff_role, staff_branch_id
  from public.demo_workspace_memberships membership
  left join public.staff_users su
    on su.workspace_id = membership.workspace_id
   and su.auth_user_id = membership.auth_user_id
   and su.is_active = true
  where membership.auth_user_id = (select auth.uid())
    and membership.workspace_id = new.workspace_id
    and membership.status = 'active'
    and membership.is_current = true
  limit 1;

  if staff_role is null or staff_role not in ('super_admin', 'branch_manager') then
    raise exception using errcode = '42501', message = 'Only active super administrators and branch managers may manage property classification.';
  end if;
  if staff_role = 'branch_manager' and (
    staff_branch_id is null or new.branch_id is distinct from staff_branch_id
    or (tg_op = 'UPDATE' and old.branch_id is distinct from staff_branch_id)
  ) then
    raise exception using errcode = '42501', message = 'Branch managers may manage properties only within their assigned branch.';
  end if;
  return new;
end;
$$;

