-- Ithaca reusable real-estate demo platform
-- Phase 1: database-enforced demo workspace isolation.
--
-- This is a forward-only, non-destructive migration. Existing Hilltop records
-- are assigned to one public/default "Hilltop Template" workspace. Workspaces
-- are archived rather than deleted and every workspace foreign key is RESTRICT.

begin;

create extension if not exists "pgcrypto";
create schema if not exists private;
revoke all on schema private from public;

create table if not exists public.demo_workspaces (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null,
  status text not null default 'active',
  is_public_default boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  constraint demo_workspaces_name_valid
    check (name = btrim(name) and char_length(name) between 2 and 120),
  constraint demo_workspaces_slug_valid
    check (slug = lower(slug) and slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$' and char_length(slug) <= 80),
  constraint demo_workspaces_status_valid
    check (status in ('active', 'archived')),
  constraint demo_workspaces_slug_key unique (slug)
);

create unique index if not exists demo_workspaces_one_public_default_idx
  on public.demo_workspaces (is_public_default)
  where is_public_default = true;

create index if not exists demo_workspaces_active_name_idx
  on public.demo_workspaces (name)
  where status = 'active';
create index if not exists demo_workspaces_created_by_idx
  on public.demo_workspaces (created_by);

drop trigger if exists trg_demo_workspaces_set_updated_at on public.demo_workspaces;
create trigger trg_demo_workspaces_set_updated_at
before update on public.demo_workspaces
for each row execute function public.set_updated_at();

create table if not exists public.demo_workspace_memberships (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.demo_workspaces(id) on delete restrict,
  auth_user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'agent',
  status text not null default 'active',
  is_current boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  constraint demo_workspace_memberships_role_valid
    check (role in ('super_admin', 'branch_manager', 'agent')),
  constraint demo_workspace_memberships_status_valid
    check (status in ('active', 'revoked')),
  constraint demo_workspace_memberships_workspace_user_key
    unique (workspace_id, auth_user_id)
);

create index if not exists demo_workspace_memberships_auth_user_idx
  on public.demo_workspace_memberships (auth_user_id, status);
create index if not exists demo_workspace_memberships_workspace_idx
  on public.demo_workspace_memberships (workspace_id, status);
create index if not exists demo_workspace_memberships_created_by_idx
  on public.demo_workspace_memberships (created_by);
create unique index if not exists demo_workspace_memberships_one_current_idx
  on public.demo_workspace_memberships (auth_user_id)
  where is_current = true;

drop trigger if exists trg_demo_workspace_memberships_set_updated_at on public.demo_workspace_memberships;
create trigger trg_demo_workspace_memberships_set_updated_at
before update on public.demo_workspace_memberships
for each row execute function public.set_updated_at();

-- Insert exactly one safe home for all pre-workspace Hilltop data. The UUID is
-- generated by Postgres and is never hard-coded in application code.
insert into public.demo_workspaces (name, slug, status, is_public_default)
values ('Hilltop Template', 'hilltop-template', 'active', true)
on conflict (slug) do update
set name = excluded.name,
    status = 'active',
    is_public_default = true;

-- Add/backfill workspace_id only on company-owned data. Geographic reference
-- tables (provinces, cities, suburbs and location_search) intentionally remain
-- global and are not included here.
do $$
declare
  table_name text;
  default_workspace_id uuid;
  company_tables constant text[] := array[
    'branches',
    'staff_users',
    'properties',
    'property_images',
    'property_documents',
    'leads',
    'activity_logs',
    'lead_communication_logs',
    'app_settings',
    'cms_homepage_content',
    'cms_banners',
    'cms_team_profiles',
    'cms_testimonials',
    'cms_featured_properties',
    'cms_service_showcase_items',
    'cms_services_section',
    'cms_service_cards',
    'team_members',
    'market_price_statistics'
  ];
begin
  select id into strict default_workspace_id
  from public.demo_workspaces
  where is_public_default = true;

  foreach table_name in array company_tables loop
    if to_regclass(format('public.%I', table_name)) is not null then
      execute format('alter table public.%I add column if not exists workspace_id uuid', table_name);
      execute format('update public.%I set workspace_id = $1 where workspace_id is null', table_name)
        using default_workspace_id;
      execute format('alter table public.%I alter column workspace_id set not null', table_name);

      if not exists (
        select 1
        from pg_constraint
        where conrelid = format('public.%I', table_name)::regclass
          and conname = table_name || '_workspace_id_fkey'
      ) then
        execute format(
          'alter table public.%I add constraint %I foreign key (workspace_id) references public.demo_workspaces(id) on delete restrict',
          table_name,
          table_name || '_workspace_id_fkey'
        );
      end if;

      execute format(
        'create index if not exists %I on public.%I (workspace_id)',
        'idx_' || table_name || '_workspace_id',
        table_name
      );

      if not exists (
        select 1
        from pg_constraint
        where conrelid = format('public.%I', table_name)::regclass
          and conname = table_name || '_id_workspace_key'
      ) then
        execute format(
          'alter table public.%I add constraint %I unique (id, workspace_id)',
          table_name,
          table_name || '_id_workspace_key'
        );
      end if;
    end if;
  end loop;
end;
$$;

