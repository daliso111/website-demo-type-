-- Remove every legacy policy from tenant-owned tables before installing the
-- current-workspace policies. Leaving one permissive legacy policy would OR
-- with the new policy and defeat isolation.
do $$
declare
  policy_record record;
  company_tables constant text[] := array[
    'branches','staff_users','properties','property_images','property_documents',
    'leads','activity_logs','lead_communication_logs','app_settings',
    'cms_homepage_content','cms_banners','cms_team_profiles','cms_testimonials',
    'cms_featured_properties','cms_service_showcase_items','cms_services_section',
    'cms_service_cards','team_members','market_price_statistics'
  ];
begin
  for policy_record in
    select tablename, policyname
    from pg_policies
    where schemaname = 'public' and tablename = any(company_tables)
  loop
    execute format('drop policy %I on public.%I', policy_record.policyname, policy_record.tablename);
  end loop;
end;
$$;

-- Common current-workspace SELECT/INSERT/UPDATE rules. Activity logs are
-- deliberately handled separately below because audit records are immutable.
do $$
declare
  table_name text;
  common_tables constant text[] := array[
    'branches','staff_users','properties','property_images','property_documents',
    'leads','lead_communication_logs','app_settings',
    'cms_homepage_content','cms_banners','cms_team_profiles','cms_testimonials',
    'cms_featured_properties','cms_service_showcase_items','team_members'
  ];
begin
  foreach table_name in array common_tables loop
    if to_regclass(format('public.%I', table_name)) is not null then
      execute format('alter table public.%I enable row level security', table_name);
      execute format(
        'create policy workspace_select on public.%I for select to authenticated using (workspace_id = (select private.current_demo_workspace_id()))',
        table_name
      );
      execute format(
        'create policy workspace_insert on public.%I for insert to authenticated with check (workspace_id = (select private.current_demo_workspace_id()))',
        table_name
      );
      execute format(
        'create policy workspace_update on public.%I for update to authenticated using (workspace_id = (select private.current_demo_workspace_id())) with check (workspace_id = (select private.current_demo_workspace_id()))',
        table_name
      );
      execute format('grant select (workspace_id) on public.%I to authenticated', table_name);
    end if;
  end loop;
end;
$$;

