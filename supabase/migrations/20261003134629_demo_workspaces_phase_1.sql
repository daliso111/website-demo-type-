-- Keep workspace membership synchronized when an Auth identity is linked to a
-- staff record. This preserves the existing manual Auth-user linking workflow.
create or replace function private.sync_staff_workspace_membership()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE'
     and old.auth_user_id is not null
     and (
       old.auth_user_id is distinct from new.auth_user_id
       or old.workspace_id is distinct from new.workspace_id
     ) then
    update public.demo_workspace_memberships
    set status = 'revoked', is_current = false, updated_at = now()
    where workspace_id = old.workspace_id
      and auth_user_id = old.auth_user_id;
  end if;

  if new.auth_user_id is null then
    return new;
  end if;

  insert into public.demo_workspace_memberships (
    workspace_id, auth_user_id, role, status, is_current, created_by
  ) values (
    new.workspace_id,
    new.auth_user_id,
    new.role,
    case when new.is_active then 'active' else 'revoked' end,
    new.is_active and not exists (
      select 1 from public.demo_workspace_memberships m
      where m.auth_user_id = new.auth_user_id and m.is_current = true
    ),
    (select auth.uid())
  )
  on conflict (workspace_id, auth_user_id) do update
  set role = excluded.role,
      status = excluded.status,
      is_current = case when excluded.status = 'revoked' then false else public.demo_workspace_memberships.is_current end,
      updated_at = now();

  return new;
end;
$$;
revoke all on function private.sync_staff_workspace_membership() from public;

drop trigger if exists trg_staff_users_sync_workspace_membership on public.staff_users;
create trigger trg_staff_users_sync_workspace_membership
after insert or update of auth_user_id, role, is_active, workspace_id on public.staff_users
for each row execute function private.sync_staff_workspace_membership();

-- Atomic, authenticated workspace lifecycle functions. There is deliberately
-- no delete function.
create or replace function public.switch_demo_workspace(p_workspace_id uuid)
returns public.demo_workspaces
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_id uuid := (select auth.uid());
  selected_workspace public.demo_workspaces;
begin
  if caller_id is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  select workspace.* into selected_workspace
  from public.demo_workspaces workspace
  join public.demo_workspace_memberships membership on membership.workspace_id = workspace.id
  where workspace.id = p_workspace_id
    and workspace.status = 'active'
    and membership.auth_user_id = caller_id
    and membership.status = 'active';

  if selected_workspace.id is null then
    raise exception using errcode = '42501', message = 'The requested workspace is unavailable.';
  end if;

  update public.demo_workspace_memberships
  set is_current = false, updated_at = now()
  where auth_user_id = caller_id and is_current = true;

  update public.demo_workspace_memberships
  set is_current = true, updated_at = now()
  where auth_user_id = caller_id and workspace_id = p_workspace_id and status = 'active';

  return selected_workspace;
end;
$$;

create or replace function public.create_demo_workspace(
  p_name text,
  p_slug text
)
returns public.demo_workspaces
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_id uuid := (select auth.uid());
  clean_name text := btrim(p_name);
  clean_slug text := lower(btrim(p_slug));
  created_workspace public.demo_workspaces;
begin
  if caller_id is null or not private.is_current_workspace_super_admin() then
    raise exception using errcode = '42501', message = 'Only an active super administrator can create a workspace.';
  end if;
  if clean_name is null or char_length(clean_name) not between 2 and 120 then
    raise exception using errcode = '22023', message = 'Workspace name must contain 2 to 120 characters.';
  end if;
  if clean_slug is null or clean_slug !~ '^[a-z0-9]+(?:-[a-z0-9]+)*$' or char_length(clean_slug) > 80 then
    raise exception using errcode = '22023', message = 'Workspace slug must use lowercase letters, numbers, and single hyphens.';
  end if;
  begin
    insert into public.demo_workspaces (name, slug, status, created_by)
    values (clean_name, clean_slug, 'active', caller_id)
    returning * into created_workspace;
  exception when unique_violation then
    raise exception using errcode = '23505', message = 'A workspace with this slug already exists.';
  end;

  insert into public.demo_workspace_memberships (
    workspace_id, auth_user_id, role, status, is_current, created_by
  ) values (
    created_workspace.id, caller_id, 'super_admin', 'active', false, caller_id
  );

  perform public.switch_demo_workspace(created_workspace.id);

  return created_workspace;
end;
$$;

create or replace function public.archive_demo_workspace(p_workspace_id uuid)
returns public.demo_workspaces
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_id uuid := (select auth.uid());
  archived_workspace public.demo_workspaces;
  fallback_workspace_id uuid;
  was_current boolean;
begin
  if caller_id is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  select workspace.*
    into archived_workspace
  from public.demo_workspaces workspace
  join public.demo_workspace_memberships membership on membership.workspace_id = workspace.id
  where workspace.id = p_workspace_id
    and membership.auth_user_id = caller_id
    and membership.status = 'active'
    and membership.role = 'super_admin';

  select membership.is_current
    into was_current
  from public.demo_workspace_memberships membership
  where membership.workspace_id = p_workspace_id
    and membership.auth_user_id = caller_id
    and membership.status = 'active';

  if archived_workspace.id is null then
    raise exception using errcode = '42501', message = 'Only a workspace super administrator can archive this workspace.';
  end if;
  if archived_workspace.is_public_default then
    raise exception using errcode = '23514', message = 'The public default workspace cannot be archived.';
  end if;

  if was_current then
    select membership.workspace_id into fallback_workspace_id
    from public.demo_workspace_memberships membership
    join public.demo_workspaces workspace on workspace.id = membership.workspace_id
    where membership.auth_user_id = caller_id
      and membership.status = 'active'
      and membership.workspace_id <> p_workspace_id
      and workspace.status = 'active'
    order by workspace.created_at
    limit 1;

    if fallback_workspace_id is null then
      raise exception using errcode = '23514', message = 'Switch to or create another active workspace before archiving this one.';
    end if;
  end if;

  update public.demo_workspaces
  set status = 'archived', updated_at = now()
  where id = p_workspace_id
  returning * into archived_workspace;

  -- Invalidate the archived selection for every member. The auth guard can
  -- then atomically recover each user to their own remaining active workspace
  -- on the next request; no stale current marker points at archived data.
  update public.demo_workspace_memberships
  set is_current = false, updated_at = now()
  where workspace_id = p_workspace_id
    and is_current = true;

  if was_current then
    update public.demo_workspace_memberships
    set is_current = true, updated_at = now()
    where auth_user_id = caller_id and workspace_id = fallback_workspace_id;
  end if;

  return archived_workspace;
end;
$$;

